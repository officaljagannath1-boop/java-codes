class while3 {
    public static void main(String[] args) {
        int i = 1;
        while (i <= 100) {
            if (i % 2 == 0) {
                System.out.println(" even  : " + i);

            } else {
                System.out.println(" odd  : " + i);

            }

            i++;
        }

    }

}
